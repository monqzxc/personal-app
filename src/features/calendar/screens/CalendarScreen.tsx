import { useCallback, useState } from 'react';
import { Image, Pressable, View, type ImageSourcePropType, type ViewStyle } from 'react-native';
import { router, useFocusEffect, useLocalSearchParams } from 'expo-router';
import { AppHeader, Button, Card, EmptyState, IconButton, Label, Screen, layout } from '../../../components/common/ui';
import { useAppStore } from '../../../stores/useAppStore';
import { useTheme } from '../../../theme/useTheme';
import { agendaForDate, buildAgenda } from '../../../services/calendarService';
import { dateOnly, formatDate, isDateOnly, localDate, monthCells } from '../../../utils/dates';
import { useToday } from '../../../hooks/useToday';
import { AgendaCard } from '../components/AgendaCard';

// Decorative artwork: white masks generated by scripts/calendar-art.mjs, stacked and tinted per theme.
function Artwork({ layers, width, height, style }: { layers: [ImageSourcePropType, string][]; width: number; height: number; style?: ViewStyle }) {
  return <View pointerEvents="none" accessible={false} accessibilityElementsHidden importantForAccessibility="no-hide-descendants" style={[{ width, height }, style]}>
    {layers.map(([source, tint], index) => <Image key={index} source={source} style={{ position: 'absolute', width, height, tintColor: tint }} />)}
  </View>;
}

export default function CalendarScreen() {
  const today = useToday();
  const { date } = useLocalSearchParams<{ date?: string }>();
  const initialDate = isDateOnly(date) ? date : today;
  const [selected, setSelected] = useState(initialDate);
  const [month, setMonth] = useState(`${initialDate.slice(0, 7)}-01`);
  useFocusEffect(useCallback(() => {
    if (isDateOnly(date)) { setSelected(date); setMonth(`${date.slice(0, 7)}-01`); router.setParams({ date: undefined }); }
  }, [date]));
  const { colors, radius, spacing, typography } = useTheme();
  const tasks = useAppStore(state => state.tasks);
  const events = useAppStore(state => state.events);
  const data = useAppStore(state => state.data);
  const agenda = buildAgenda(events, tasks, data, Number(month.slice(0, 4)));
  const visible = agendaForDate(agenda, selected);
  function moveMonth(offset: number) {
    const next = localDate(month);
    next.setMonth(next.getMonth() + offset);
    const value = dateOnly(next);
    setMonth(value);
    setSelected(value);
  }
  return <Screen>
    <View>
      {/* The spirit bleeds into the screen's top-right padding, behind the title. */}
      <Artwork width={230} height={160} style={{ position: 'absolute', top: -spacing.xl, right: -spacing.xl }}
        layers={[[require('../../../../assets/calendar-spirit-shade.png'), colors.artShade], [require('../../../../assets/calendar-spirit-light.png'), colors.artLight]]} />
      <AppHeader eyebrow="Your calendar" title="A little perspective." />
      <View style={{ width: 24, height: 3, borderRadius: 2, marginTop: spacing.md, backgroundColor: colors.primary }} />
    </View>
    <Card>
      <View style={[layout.row, { justifyContent: 'space-between' }]}>
        <IconButton icon="chevron-back" label="Previous month" onPress={() => moveMonth(-1)} />
        <Label size={18} bold style={{ flex: 1, textAlign: 'center' }}>{localDate(month).toLocaleDateString(undefined, { month: 'long', year: 'numeric' })}</Label>
        <IconButton icon="chevron-forward" label="Next month" onPress={() => moveMonth(1)} />
      </View>
      <View style={{ flexDirection: 'row', flexWrap: 'wrap' }}>
        {['S', 'M', 'T', 'W', 'T', 'F', 'S'].map((day, index) => <View key={`header-${index}`} style={{ width: '14.2857%', alignItems: 'center', paddingVertical: spacing.sm }}><Label muted size={12}>{day}</Label></View>)}
        {monthCells(month).map((date, index) => <View key={date ?? `blank-${index}`} style={{ width: '14.2857%', padding: 2 }}>
          {date ? <Pressable accessibilityRole="button" accessibilityLabel={localDate(date).toLocaleDateString(undefined, { dateStyle: 'full' })} accessibilityState={{ selected: selected === date }}
            onPress={() => setSelected(date)} style={{ minHeight: 50, borderRadius: 14, alignItems: 'center', justifyContent: 'center', gap: 4,
              backgroundColor: selected === date ? colors.primary : date === today ? colors.primarySoft : colors.transparent }}>
            <Label size={15} bold={date === today || date === selected} color={selected === date ? colors.onPrimary : colors.text}>{Number(date.slice(-2))}</Label>
            <View style={{ width: 5, height: 5, borderRadius: 3, backgroundColor: agendaForDate(agenda, date).length ? selected === date ? colors.onPrimary : colors.primary : colors.transparent }} />
          </Pressable> : <View style={{ minHeight: 50 }} />}
        </View>)}
      </View>
      <View style={[layout.row, { marginTop: spacing.xs }]}>
        <View style={{ flex: 1, height: 1, backgroundColor: colors.border }} />
        <Pressable accessibilityRole="button" onPress={() => { setSelected(today); setMonth(`${today.slice(0, 7)}-01`); }}
          style={({ pressed }) => ({ minHeight: 44, paddingHorizontal: spacing.xxl, borderRadius: radius.pill, alignItems: 'center', justifyContent: 'center', backgroundColor: colors.surfaceAlt, opacity: pressed ? 0.75 : 1 })}>
          <Label bold color={colors.primary}>Back to today</Label>
        </Pressable>
        <View style={{ flex: 1, height: 1, backgroundColor: colors.border }} />
      </View>
    </Card>
    <View style={layout.row}>
      <Label size={typography.title} bold style={{ flex: 1 }}>{selected === today ? 'Today’s agenda' : formatDate(selected)}</Label>
      <Artwork width={130} height={56} layers={[[require('../../../../assets/agenda-ghost-body.png'), colors.artLight], [require('../../../../assets/agenda-ghost-face.png'), colors.onIndicator]]} />
    </View>
    <Button title="Add an event" variant="secondary" icon="add" onPress={() => router.push({ pathname: '/event', params: { date: selected } })} />
    {visible.map(item => <AgendaCard key={item.id} item={item} day={selected} />)}
    {!visible.length && <EmptyState icon="sunny-outline" title="An open day" description="Your events and active task deadlines will appear here." />}
    <Button title="Device calendar integration" variant="ghost" onPress={() => router.push('/calendar-integration')} />
    <Label muted size={12}>Events, deadlines, payments, trips, renewals, and important dates</Label>
  </Screen>;
}
